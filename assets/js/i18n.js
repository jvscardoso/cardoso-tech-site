  const STORAGE_KEY = "ct-lang";

  function getInitialLang() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && dict[saved]) return saved;
    } catch (e) {}
    return (navigator.language || "pt").toLowerCase().startsWith("pt") ? "pt" : "en";
  }

  function apply(lang) {
    const t = dict[lang];
    document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
    document.title = t[document.body.dataset.page === "privacy" ? "meta.privacy" : "meta.home"];

    document.querySelectorAll("[data-i18n]").forEach(el => {
      const v = t[el.dataset.i18n];
      if (v !== undefined) el.textContent = v;
    });
    document.querySelectorAll("[data-i18n-html]").forEach(el => {
      const v = t[el.dataset.i18nHtml];
      if (v !== undefined) el.innerHTML = v;
    });
    document.querySelectorAll(".lang-switch button").forEach(b => {
      b.setAttribute("aria-pressed", String(b.dataset.lang === lang));
    });
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
  }

  document.querySelectorAll(".lang-switch button").forEach(b => {
    b.addEventListener("click", () => apply(b.dataset.lang));
  });

  apply(getInitialLang());

  const year = document.getElementById("year");
  if (year) year.textContent = new Date().getFullYear();

  // Reveal on scroll
  const targets = document.querySelectorAll(".card, .product, .steps li, .contact, .section-head");
  if ("IntersectionObserver" in window) {
    const io = new IntersectionObserver(entries => {
      entries.forEach(e => {
        if (e.isIntersecting) { e.target.classList.add("in"); io.unobserve(e.target); }
      });
    }, { threshold: 0.12 });
    targets.forEach(el => { el.classList.add("reveal"); io.observe(el); });
  }
